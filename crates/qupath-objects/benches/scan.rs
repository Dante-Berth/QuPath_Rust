//! Scan and filter one feature across a large detection table.
//!
//! Mirrors `parity/java/BenchMeasurementScan.java` exactly — same object count,
//! same feature count, same target feature, same threshold — so the two results
//! can be compared. Run both on the same machine; see `docs/benchmarks/`.
//!
//! Construction is excluded from timing on both sides.

use criterion::{Criterion, criterion_main};
use qupath_objects::{FeatureId, Table};
use std::hint::black_box;

const N_OBJECTS: usize = 1_000_000;
const N_FEATURES: usize = 20;
const TARGET: &str = "Feature 13";

/// Builds the table both sides measure: `N_OBJECTS` rows, `N_FEATURES` columns,
/// values matching `BenchMeasurementScan.java` exactly.
fn build() -> Table {
    let mut table = Table::new();
    let features: Vec<FeatureId> = (0..N_FEATURES)
        .map(|f| table.add_feature(&format!("Feature {f}")))
        .collect();
    let rows: Vec<_> = table.push_objects(N_OBJECTS).collect();

    for (i, &row) in rows.iter().enumerate() {
        for (f, &feature) in features.iter().enumerate() {
            #[expect(
                clippy::cast_precision_loss,
                reason = "values are (i * 31 + f) % 1000, well within f32"
            )]
            let value = ((i * 31 + f) % 1000) as f32;
            table.set(row, feature, value);
        }
    }
    table.shrink_to_fit();
    table
}

/// Sum of `Feature 13` over all rows, and the count above the filter threshold.
///
/// Both benchmarks must agree with these, and so must the Java side — a
/// benchmark whose result is wrong is measuring the wrong thing, and the usual
/// way a scan gets fast is by not happening.
const EXPECTED_SUM: f64 = 499_500_000.0;
const EXPECTED_COUNT: u64 = 499_000;

fn bench(c: &mut Criterion) {
    let table = build();
    let target = table.feature(TARGET).expect("target feature was added");

    {
        let column = table.column(target);
        let sum: f64 = column.iter().map(|&v| f64::from(v)).sum();
        assert_eq!(
            sum, EXPECTED_SUM,
            "scan does not compute the expected sum; the benchmark is invalid"
        );
        let count = column.iter().filter(|&&v| v > 500.0).count() as u64;
        assert_eq!(
            count, EXPECTED_COUNT,
            "filter does not compute the expected count; the benchmark is invalid"
        );
    }

    let mut group = c.benchmark_group("measurement");
    group.throughput(criterion::Throughput::Elements(N_OBJECTS as u64));

    // Sum one feature across every object.
    group.bench_function("scan", |b| {
        b.iter(|| {
            let column = black_box(&table).column(black_box(target));
            let mut total = 0.0_f64;
            for &v in column {
                total += f64::from(v);
            }
            black_box(total)
        });
    });

    // Count objects whose target feature exceeds a threshold.
    group.bench_function("filter", |b| {
        b.iter(|| {
            let column = black_box(&table).column(black_box(target));
            let mut n = 0_u64;
            for &v in column {
                if v > 500.0 {
                    n += 1;
                }
            }
            black_box(n)
        });
    });

    // Filtering to an index list, which is what callers actually want.
    group.bench_function("filter_to_indices", |b| {
        b.iter(|| black_box(black_box(&table).filter(target, |v| v > 500.0).len()));
    });

    group.finish();
}

// `criterion_group!` generates a public item that carries no doc comment; the
// workspace `missing_docs` lint cannot see inside the expansion to fix it.
#[allow(missing_docs, reason = "item is generated by criterion_group!")]
mod harness {
    use criterion::criterion_group;

    criterion_group!(benches, super::bench);
}

criterion_main!(harness::benches);
