#!/usr/bin/env bash
# Profile QuPath's watershed cell detection with JFR, per §3 of the project
# guidelines: no subsystem is ported before a profile of the equivalent QuPath
# path exists.
#
# Usage: ./profile/run.sh [slide] [x y w h] [warmup] [timed]
#
# Needs JDK 25+ on PATH, or JAVA_HOME pointing at one — see parity/README.md.
# Writes docs/profiles/<slide>-cells.jfr plus a text summary beside it.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

slide="${1:-$root/data/CMU-1.svs}"
x="${2:-20000}"
y="${3:-15000}"
w="${4:-4000}"
h="${5:-4000}"
warmup="${6:-2}"
timed="${7:-5}"

if [[ ! -f "$slide" ]]; then
    echo "error: slide not found: $slide" >&2
    echo "       see docs/test-data.md for how to fetch it" >&2
    exit 1
fi

# Bio-Formats reads SVS in pure Java; the OpenSlide extension would need a
# native library that is not a dependency of this repository yet.
modules=(qupath-core qupath-core-processing qupath-extension-bioformats)
# shellcheck source=parity/classpath.sh
source "$root/parity/classpath.sh"

out="$root/docs/profiles"
mkdir -p "$out"
name="$(basename "$slide" .svs)-cells"
jfr="$out/$name.jfr"
log="$out/$name.log"

# Compiled to a class directory rather than run in source-file mode: the driver
# calls the package-private CellDetector, and package-private access needs the
# same classloader, which source-file mode's MemoryClassLoader is not.
classes="$root/profile/build"
mkdir -p "$classes"
"${java_bin%java}javac" -nowarn -cp "$cp" -d "$classes" \
    "$root/profile/java/qupath/imagej/detect/cells/ProfileCellDetection.java"

echo "==> profiling $(basename "$slide") ${w}x${h} at $x,$y" >&2

# settings=profile raises the sampling rate over the default; the JFR recording
# covers the whole JVM, so warmup and slide-opening cost are in the file too and
# are separated out by the summary below.
"$java_bin" \
    -XX:+UnlockDiagnosticVMOptions \
    -XX:+DebugNonSafepoints \
    -XX:StartFlightRecording="settings=profile,filename=$jfr,dumponexit=true" \
    -cp "$cp$classes" \
    qupath.imagej.detect.cells.ProfileCellDetection \
    "$slide" "$x" "$y" "$w" "$h" "$warmup" "$timed" 2>&1 | tee "$log" >&2

echo "==> $jfr" >&2

# Top frames by self time. This is the number §3 asks to be named in the PR.
summary="$out/$name-hot.txt"
{
    echo "# Top frames by self time — $(basename "$slide")"
    echo "# region ${w}x${h} at $x,$y; $warmup warmup + $timed timed iterations"
    echo "# generated by profile/run.sh; do not edit"
    echo
    # The top line of each stackTrace is the frame executing when sampled, so
    # counting only those gives self time. --stack-depth 1 keeps jfr from
    # truncating with "..." before we see it.
    "${java_bin%java}jfr" print --events jdk.ExecutionSample --stack-depth 1 "$jfr" \
        | grep -A1 'stackTrace = \[' \
        | grep -oP '^\s+\K[a-zA-Z_$][\w.$]*\.[\w$<>]+(?=\()' \
        | sort | uniq -c | sort -rn | head -40
} >"$summary"

echo "==> $summary" >&2
sed -n '5,20p' "$summary" >&2
