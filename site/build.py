#!/usr/bin/env python3
"""Build the documentation site: the repository's Markdown as an mdBook, with
the rustdoc API reference beside it.

    python3 site/build.py            # book and API docs -> target/site/book
    python3 site/build.py --no-api   # the book alone, without running cargo doc

Pages are staged at their repository paths, so a relative link that works on
GitHub works on the site unchanged. A link to anything the site does not carry
(a source file, a fixture, a script) is rewritten to the file on GitHub rather
than left to 404. After building, every relative link in the output is checked
and the build fails naming any that does not resolve.
"""

import argparse
import re
import shutil
import subprocess
import sys
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parent.parent
STAGE = ROOT / "target" / "site" / "src"
BOOK = ROOT / "target" / "site" / "book"
BLOB = "https://github.com/Dante-Berth/QuPath_Rust/blob/main/"
TREE = "https://github.com/Dante-Berth/QuPath_Rust/tree/main/"
SITE_URL = "/QuPath_Rust/"  # book.toml's site-url: where GitHub Pages serves it

# (title, repository path, depth), in reading order. `None` as a path starts a
# part. Every page here is staged; nothing else is.
CHAPTERS = [
    ("Introduction", "README.md", 0),
    ("User guide", None, 0),
    ("Overview", "docs/guide/README.md", 0),
    ("Installing and building", "docs/guide/installing.md", 1),
    ("Viewing a slide", "docs/guide/viewing.md", 1),
    ("Detecting cells", "docs/guide/detecting.md", 1),
    ("Projects", "docs/guide/projects.md", 1),
    ("Exporting to QuPath", "docs/guide/exporting.md", 1),
    ("Parity and what to trust", "docs/guide/parity.md", 1),
    ("Command-line tools", "docs/guide/command-line.md", 1),
    ("Test data", "docs/test-data.md", 0),
    ("The project", None, 0),
    ("Status in detail", "docs/STATUS.md", 0),
    ("Divergences from QuPath", "DIVERGENCES.md", 0),
    ("Benchmarks", "docs/benchmarks/README.md", 0),
    ("Profiles", "docs/profiles/README.md", 0),
    ("Parity fixtures", "parity/README.md", 0),
    ("Presentation", "presentation/README.md", 0),
    ("Contributing", "CONTRIBUTING.md", 0),
    ("API reference", "api.md", 0),
    ("Design records", None, 0),
    ("Memo", "docs/dev/MEMO.md", 0),
    ("Roadmap", "docs/dev/ROADMAP.md", 0),
    ("Formats", "docs/dev/FORMATS.md", 0),
    ("The viewer", "docs/dev/VIEWER.md", 0),
    ("Evolution", "docs/dev/EVOLUTION.md", 0),
    ("Rust guidelines", "docs/dev/rust-guidelines/README.md", 0),
]

# Linked files the site carries itself rather than sending to GitHub: pictures,
# so pages render, and the deck, so it downloads from where it is described.
ASSETS = {".svg", ".png", ".jpg", ".jpeg", ".gif", ".pptx"}

LINK = re.compile(r"(!?\[[^\]]*\])\(([^)\s]+)\)")


def crates():
    return sorted(p.parent.name for p in (ROOT / "crates").glob("*/Cargo.toml"))


def api_page():
    rows = "\n".join(
        f"- [`{c}`](api/{c.replace('-', '_')}/index.html)" for c in crates()
    )
    return (
        "# API reference\n\n"
        "Generated by `cargo doc` from the doc comments, so it cannot fall out\n"
        "of step with the code. Each crate's page opens with what QuPath does,\n"
        "what this does instead, and what the difference is worth.\n\n"
        f"{rows}\n"
    )


def rewrite(page: str, text: str, pages: set, copied: set) -> str:
    """Point every relative link at something the site has, or at GitHub."""
    base = Path(page).parent

    def fix(m):
        label, target = m.group(1), m.group(2)
        if re.match(r"[a-z]+:", target) or target.startswith("#"):
            return m.group(0)
        path, _, frag = target.partition("#")
        rel = (base / unquote(path)).as_posix()
        if not (ROOT / rel).exists():
            return m.group(0)  # dangling on GitHub too; the checker reports it
        repo = (ROOT / rel).resolve().relative_to(ROOT).as_posix()
        anchor = f"#{frag}" if frag else ""
        # mdBook publishes each README.md as index.html and does not follow
        # links to it, so they are pointed at the name it publishes.
        if repo in pages:
            if Path(repo).name == "README.md":
                return f"{label}({path[: -len('README.md')]}index.md{anchor})"
            return m.group(0)
        if (ROOT / repo).is_dir():
            if f"{repo}/README.md" in pages:
                return f"{label}({path.rstrip('/')}/index.md{anchor})"
            return f"{label}({TREE}{repo})"
        if Path(repo).suffix.lower() in ASSETS:
            copied.add(repo)
            return m.group(0)
        return f"{label}({BLOB}{repo}{anchor})"

    return LINK.sub(fix, text)


def stage():
    if STAGE.exists():
        shutil.rmtree(STAGE)
    STAGE.mkdir(parents=True)
    pages = {p for _, p, _ in CHAPTERS if p and p != "api.md"}
    copied = set()
    for page in sorted(pages):
        text = (ROOT / page).read_text(encoding="utf-8")
        out = STAGE / page
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(rewrite(page, text, pages, copied), encoding="utf-8")
    for asset in sorted(copied):
        (STAGE / asset).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / asset, STAGE / asset)
    (STAGE / "api.md").write_text(api_page(), encoding="utf-8")

    summary = ["# Summary", ""]
    for title, path, depth in CHAPTERS:
        if path is None:
            summary += ["", f"# {title}", ""]
        elif path == "README.md":
            summary.append(f"[{title}]({path})")
        else:
            summary.append(f"{'  ' * depth}- [{title}]({path})")
    (STAGE / "SUMMARY.md").write_text("\n".join(summary) + "\n", encoding="utf-8")
    return len(pages) + 1, len(copied)


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.found = []

    def handle_starttag(self, tag, attrs):
        for k, v in attrs:
            if k in ("href", "src") and v:
                self.found.append(v)


def check():
    """Every relative href and src in the built site must name a file in it."""
    bad = []
    for html in BOOK.rglob("*.html"):
        if (BOOK / "api") in html.parents:
            continue  # rustdoc checks its own links under -D warnings
        parser = Links()
        parser.feed(html.read_text(encoding="utf-8"))
        for link in parser.found:
            if re.match(r"[a-z]+:|#|//", link):
                continue
            path = unquote(link.split("#")[0].split("?")[0])
            if not path:
                continue
            if path.startswith(SITE_URL):  # site-rooted, as the 404 page links
                target = BOOK / path[len(SITE_URL):]
            else:
                target = (html.parent / path).resolve()
            if target.is_dir():
                target = target / "index.html"
            if not target.exists():
                bad.append(f"{html.relative_to(BOOK)} -> {link}")
    return sorted(set(bad))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--no-api", action="store_true", help="skip cargo doc")
    args = ap.parse_args()

    n_pages, n_assets = stage()
    subprocess.run(["mdbook", "build", str(ROOT / "site")], check=True)
    if not args.no_api:
        subprocess.run(
            ["cargo", "doc", "--workspace", "--no-deps", "--locked"],
            cwd=ROOT, check=True,
        )
        shutil.copytree(ROOT / "target" / "doc", BOOK / "api", dirs_exist_ok=True)

    bad = check()
    if args.no_api:
        bad = [b for b in bad if "-> api/" not in b]
    print(f"{n_pages} pages, {n_assets} assets -> {BOOK.relative_to(ROOT)}")
    if bad:
        print(f"{len(bad)} broken links:", *bad, sep="\n  ", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
